create table public.tens_in_groups (
  id bigint generated by default as identity primary key,
  group_name text not null,
  group_pin text not null,
  state jsonb not null,
  updated_at timestamptz not null default now(),
  created_at timestamptz default now(),
  admin_name text,
  admin_contact text,
  plan_type text default 'trial',
  trial_start_date date default current_date,
  trial_expiry_date date default (current_date + 14),
  paid_status text default 'unpaid',
  renewal_date date,
  status text default 'active',
  notes text
);
create table public.iig_notification_settings (
  group_pin text primary key,
  enabled boolean not null default false,
  timezone text not null default 'Europe/London',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table public.iig_notification_events (
  id uuid primary key default gen_random_uuid(),
  group_pin text not null,
  round_key text not null,
  event_type text not null,
  title text not null default 'I''m In Golf',
  message text not null,
  scheduled_for timestamptz not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  unique (group_pin, round_key, event_type)
);
create index iig_notification_events_due_idx on public.iig_notification_events(status,scheduled_for);
