-- Access and notification function bodies supplied by the owner on 22 October 2026.
create function public.get_group_access_status(p_pin text)
returns table(group_pin text,group_name text,plan_type text,trial_expiry_date date,paid_status text,renewal_date date,status text,access_allowed boolean,access_reason text)
language plpgsql security definer set search_path to 'public' as $function$
begin
  return query select g.group_pin,g.group_name,g.plan_type,g.trial_expiry_date,g.paid_status,g.renewal_date,g.status,
  case when g.status='suspended' then false
       when g.plan_type='trial' and g.trial_expiry_date is not null and g.trial_expiry_date<current_date then false
       else true end,
  case when g.status='suspended' then 'suspended'
       when g.plan_type='trial' and g.trial_expiry_date is not null and g.trial_expiry_date<current_date then 'trial_expired'
       else 'active' end
  from public.tens_in_groups g where g.group_pin=p_pin;
end;
$function$;

create function public.iig_enable_notifications_for_new_group()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  insert into public.iig_notification_settings(group_pin,enabled,timezone)
  values(new.group_pin,true,'Europe/London')
  on conflict(group_pin) do update set enabled=true,updated_at=now();
  return new;
end;
$function$;

create function public.iig_create_notification_events()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare
  v_new_state jsonb := coalesce(new.state, '{}'::jsonb);
  v_old_state jsonb := coalesce(old.state, '{}'::jsonb);
  v_is_open boolean := coalesce(v_new_state->>'roundOpen', 'false') = 'true';
  v_was_open boolean := coalesce(v_old_state->>'roundOpen', 'false') = 'true';
  v_course text := nullif(trim(v_new_state->>'course'), '');
  v_old_course text := nullif(trim(v_old_state->>'course'), '');
  v_date date;
  v_old_date date;
  v_history_count integer := 0;
  v_round_key text;
  v_timezone text := 'Europe/London';
  v_three_days timestamptz;
  v_night_before timestamptz;
  v_new_entrants integer := 0;
  v_old_entrants integer := 0;
  v_first_player text;
begin
  if not exists (
    select 1 from public.iig_notification_settings
    where group_pin = new.group_pin and enabled = true
  ) then return new; end if;

  if not v_is_open then
    update public.iig_notification_events
    set status = 'cancelled', last_error = 'Round closed before reminder was sent'
    where group_pin = new.group_pin and status = 'pending'
      and event_type in ('three_days_before', 'night_before');
    return new;
  end if;
  begin
    v_date := nullif(v_new_state->>'date', '')::date;
  exception when others then return new;
  end;
  begin
    v_old_date := nullif(v_old_state->>'date', '')::date;
  exception when others then v_old_date := null;
  end;
  if v_course is null or v_date is null then return new; end if;
  if jsonb_typeof(v_new_state->'history') = 'array' then
    v_history_count := jsonb_array_length(v_new_state->'history');
  end if;
  v_round_key := concat(v_date::text, '|', lower(v_course), '|', v_history_count::text);
  select coalesce(timezone, 'Europe/London') into v_timezone
  from public.iig_notification_settings where group_pin = new.group_pin;
  v_timezone := coalesce(v_timezone, 'Europe/London');

  if not v_was_open or v_old_date is distinct from v_date or v_old_course is distinct from v_course then
    update public.iig_notification_events
    set status = 'cancelled', last_error = 'Competition details changed'
    where group_pin = new.group_pin and status = 'pending' and round_key <> v_round_key;
    insert into public.iig_notification_events(group_pin,round_key,event_type,title,message,scheduled_for)
    values(new.group_pin,v_round_key,'competition_created','New competition is ready ⛳',
      concat(v_course, ' is set for ', to_char(v_date, 'FMDay, FMDD FMMonth'), '. Open I''m In Golf to enter.'),now())
    on conflict(group_pin,round_key,event_type) do nothing;
    v_three_days := (((v_date - 3)::date + time '18:00') at time zone v_timezone);
    if v_three_days > now() then
      insert into public.iig_notification_events(group_pin,round_key,event_type,title,message,scheduled_for)
      values(new.group_pin,v_round_key,'three_days_before','3 days to go ⛳',
        concat(v_course, ' is this ', to_char(v_date, 'FMDay'), '. Check your entry in I''m In Golf.'),v_three_days)
      on conflict(group_pin,round_key,event_type) do nothing;
    end if;
    v_night_before := (((v_date - 1)::date + time '18:00') at time zone v_timezone);
    if v_night_before > now() then
      insert into public.iig_notification_events(group_pin,round_key,event_type,title,message,scheduled_for)
      values(new.group_pin,v_round_key,'night_before','Golf tomorrow ⛳',
        concat(v_course, ' is tomorrow. Check your entry and have a great round!'),v_night_before)
      on conflict(group_pin,round_key,event_type) do nothing;
    end if;
  end if;
  select count(*)::integer into v_new_entrants
  from jsonb_array_elements(case when jsonb_typeof(v_new_state->'players') = 'array' then v_new_state->'players' else '[]'::jsonb end) player
  where player->>'paid' = 'true' or nullif(player->>'competition', '') is not null;
  select count(*)::integer into v_old_entrants
  from jsonb_array_elements(case when jsonb_typeof(v_old_state->'players') = 'array' then v_old_state->'players' else '[]'::jsonb end) player
  where player->>'paid' = 'true' or nullif(player->>'competition', '') is not null;
  if v_old_entrants = 0 and v_new_entrants > 0 then
    select player->>'name' into v_first_player
    from jsonb_array_elements(case when jsonb_typeof(v_new_state->'players') = 'array' then v_new_state->'players' else '[]'::jsonb end) player
    where player->>'paid' = 'true' or nullif(player->>'competition', '') is not null limit 1;
    insert into public.iig_notification_events(group_pin,round_key,event_type,title,message,scheduled_for)
    values(new.group_pin,v_round_key,'first_player_joined','The first player is in 🙌',
      concat(coalesce(v_first_player, 'Someone'), ' has entered ', v_course, '. Anyone else in?'),now())
    on conflict(group_pin,round_key,event_type) do nothing;
  end if;
  return new;
end;
$function$;
create trigger iig_create_notification_events_trigger after update of state on public.tens_in_groups
for each row execute function public.iig_create_notification_events();
create trigger iig_enable_notifications_for_new_group_trigger after insert on public.tens_in_groups
for each row execute function public.iig_enable_notifications_for_new_group();
